def _context_block(
    now: datetime | None,
    *,
    patient_bound: bool,
    role: str | None = None,
) -> str:
    current = clinic_now(now)
    jalali = jdatetime.datetime.fromgregorian(datetime=current)
    lines = [
        "## زمینه (توسط سرور تعیین شده است)",
        (
            f"- اکنون به وقت تهران: {_WEEKDAYS[current.weekday()]} "
            f"{jalali.strftime('%Y/%m/%d')} ساعت {jalali.strftime('%H:%M')} "
            f"(میلادی {current.strftime('%Y-%m-%d')})."
        ),
        (
            "- قالب تاریخ در Toolها جلالی و به‌صورت `YYYY/MM/DD` "
            "(مثل `1405/08/15`) و ساعت `HH:MM` به‌صورت ۲۴ساعته است؛ "
            "ارقام لاتین بفرست. تاریخ جلالی را با میلادی اشتباه نگیر."
        ),
    ]
    if patient_bound:
        lines.append(
            "- هویت بیمار از حساب کاربری واردشده تعیین می‌شود و خودکار به "
            "Toolها داده می‌شود؛ شمارهٔ بیمار، کد ملی، نام یا تلفن را نپرس و "
            "به‌عنوان آرگومان Tool نفرست. اگر حساب چند پرونده دارد، انتخاب "
            "بیمار را از کارت‌های سرور بگیر و حدس نزن."
        )
        lines.append(
            "- برای دیدن پرونده‌های همین حساب از `get_my_profile` و برای ثبت "
            "گزارش خطا یا پیشنهاد از `submit_feedback` استفاده کن."
        )
    else:
        lines.append(
            "- برای رزرو باید بیمار مشخص باشد: یا `patient_id`، یا هر سه مورد "
            "`national_id` و `full_name` و `phone`."
        )
        lines.append(
            "- تو یک حساب کارکنان هستی؛ ابزارهای جست‌وجوی بیمار، کارت خلاصهٔ "
            "بیمار، برنامهٔ روزانهٔ پزشک و گزارش‌های کلینیک در دسترس تو هستند. "
            "برای پیدا کردن patient_id از `search_patients` استفاده کن و کد "
            "ملی پوشانده‌شده را کامل نگو."
        )
        if role in ("admin", "receptionist"):
            lines.append(
                "- ثبت پروندهٔ جدید با `create_patient` و ویرایش پرونده با "
                "`update_patient` در دسترس تو است؛ هر دو فقط با تأیید گراف "
                "اجرا می‌شوند."
            )
        lines.append(
            "- خلاصهٔ بالینی بیمار (حساسیت‌ها، سوابق درمانی، چارت دندان و "
            "طرح درمان) با `get_patient_clinical_summary` در دسترس تو است."
        )
        if role == "doctor":
            lines.append(
                "- به‌عنوان پزشک، پیش‌نویس طرح درمان را با "
                "`create_treatment_plan_draft` پیشنهاد می‌دهی؛ پیش‌نویس "
                "فقط با تأیید گراف ثبت می‌شود و طرح نهایی محسوب نمی‌شود."
            )
        if role == "admin":
            lines.append(
                "- به‌عنوان مدیر، مرور حساب‌ها با `get_staff_directory`، "
                "رخدادهای حساس با `get_audit_trail` و بازخوردها با "
                "`get_user_reports_summary` هم در دسترس تو است."
            )
    return "\n".join(lines)


